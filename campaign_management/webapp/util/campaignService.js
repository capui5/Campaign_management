sap.ui.define([
	"sap/ui/model/json/JSONModel",
	"sap/ui/model/Filter",
	"sap/ui/model/FilterOperator"
], function (JSONModel, Filter, FilterOperator) {
	"use strict";

	// Campaign master service facade (Campaign Management FDD/TDD v1.1, §4.1, §4.3, §5, §8).
	//
	// Scope: campaign code only (create / change / display / search). VK11 pricing conditions,
	// the Axxx key configuration and activation are out of scope for this screen.
	//
	// The UI talks only to this module; every public method returns a Promise.
	//
	// Backend: mainModel (ZSDGW_CE_APP_SRV), entity set CampaignsdSet over ZSD_CAMPAIGN (the older
	// CampaignSet is the per-article campaign lookup used by sales order pricing and requires
	// condition filters, so it is not used here):
	//   read    CampaignsdSet                                  search all
	//           CampaignsdSet?$filter=Country eq 'SG'          search by country
	//           CampaignsdSet?$filter=CampaignId eq 'C-...'    single campaign / search by campaign ID
	//   create  POST CampaignsdSet                CampaignIdDesc and Country only; the CampaignId is
	//                                             generated by S/4 (ZCAMPAIGN, prefix "C-") and returned
	//   change  POST CampaignsdSet                same entity and payload, with the CampaignId filled;
	//                                             CampaignId and Description mandatory
	// No validity dates are sent.
	// CampaignsdSet has no status or changed-by fields: the status shown is derived from validity.
	// Countries come from CountrySet, limited to the Luxasia markets (same list as the country
	// selection app). The default country is the selected store's country (when the launchpad has
	// one in localStorage), else the logged-in sales employee's Land: the user's e-mail from the
	// approuter user API, then the SalesEmployees function import.
	//
	// Property names are mapped once in FIELD so they can follow whatever the backend exposes.

	var CAMPAIGN_SET = "/CampaignsdSet";

	// ZSD_CAMPAIGN field -> CampaignsdSet property.
	var FIELD = {
		id: "CampaignId",          // CAMPAIGN
		description: "CampaignIdDesc", // CPNDESC
		country: "Country",        // LAND1
		createdOn: "Credate",      // ERDAT, Edm.String YYYYMMDD
		createdBy: "Crename",      // ERNAM
		validFrom: "ValidFrom",    // DATFR, Edm.DateTime
		validTo: "ValidTo"         // DATTO, Edm.DateTime
	};

	// Only these countries can be selected, defaulted or saved.
	var ALLOWED_COUNTRIES = ["SG", "MY", "TH", "PH", "VN", "ID", "IN", "AU", "HK", "TW", "CN"];

	var DESCRIPTION_MAX = 50; // CPNDESC length in the existing Campaign entity

	// Status derived from validity (no status field on the backend).
	var STATUS = {
		ACTIVE: "Active",
		UPCOMING: "Upcoming",
		EXPIRED: "Expired"
	};

	var STATUS_STATE = {
		"Active": "Success",
		"Upcoming": "Information",
		"Expired": "Error"
	};

	var _oComponent = null;
	var _oModel = null;
	var _pLoad = null;
	var _pEmployee = null;
	var _sEmployeeCountry = "";
	// ---------------------------------------------------------------- messages

	function _throw(aMsg) {
		var aList = Array.isArray(aMsg) ? aMsg : [aMsg];
		var oErr = new Error(aList[0].text);
		oErr.messages = aList;
		return oErr;
	}

	function _err(sText, sField) {
		return { type: "Error", text: sText, field: sField || "" };
	}

	// SAP Gateway error body -> messages (same parsing as the STO / PO screens).
	function _fromODataError(oError) {
		var aMsg = [];
		try {
			var oBody = JSON.parse(oError.responseText).error;
			((oBody.innererror && oBody.innererror.errordetails) || []).forEach(function (d) {
				if (d.severity !== "info") {
					aMsg.push(_err(d.message, d.target));
				}
			});
			if (!aMsg.length && oBody.message) {
				aMsg.push(_err(oBody.message.value || oBody.message));
			}
		} catch (e) {
			// not a Gateway JSON body
		}
		if (!aMsg.length) {
			aMsg.push(_err((oError && (oError.message || oError.statusText)) || "Request failed."));
		}
		var oErr = _throw(aMsg);
		oErr.statusCode = oError && String(oError.statusCode);
		return oErr;
	}

	// ---------------------------------------------------------------- backend calls

	function _main() {
		return _oComponent.getModel("mainModel");
	}

	function _read(sPath, mParameters) {
		return new Promise(function (resolve, reject) {
			_main().read(sPath, Object.assign({}, mParameters, {
				success: function (oData) { resolve(oData.results || oData); },
				error: function (oError) { reject(_fromODataError(oError)); }
			}));
		});
	}

	// Create sends only description and country; change adds the CampaignId.
	function _payload(sId, oDraft) {
		var oPayload = {};
		if (sId) {
			oPayload[FIELD.id] = sId;
		}
		oPayload[FIELD.description] = oDraft.description.trim();
		oPayload[FIELD.country] = oDraft.country;
		return oPayload;
	}

	function _post(oPayload) {
		return new Promise(function (resolve, reject) {
			_main().create(CAMPAIGN_SET, oPayload, {
				success: function (oData) { resolve(oData || {}); },
				error: function (oError) { reject(_fromODataError(oError)); }
			});
		});
	}

	// ---------------------------------------------------------------- mapping

	// Edm.DateTime comes as UTC midnight; the UI works with local calendar dates. The backend may
	// also send the dates as strings (YYYYMMDD, "/Date(ms)/" or ISO), so accept those too.
	function _toLocalDate(d) {
		if (!d) {
			return null;
		}
		if (typeof d === "string") {
			var oYmd = _parseYmd(d);
			if (oYmd || /^0+$/.test(d)) {
				return oYmd;
			}
			var aMs = /^\/Date\((-?\d+)/.exec(d);
			d = aMs ? new Date(+aMs[1]) : new Date(d);
		}
		if (!(d instanceof Date) || isNaN(d.getTime())) {
			return null;
		}
		return new Date(d.getUTCFullYear(), d.getUTCMonth(), d.getUTCDate());
	}

	// Credate is a plain YYYYMMDD string.
	function _parseYmd(s) {
		var a = /^(\d{4})(\d{2})(\d{2})$/.exec(s || "");
		return a && a[1] !== "0000" ? new Date(+a[1], +a[2] - 1, +a[3]) : null;
	}

	// No validity dates means the campaign is not limited (legacy DATFR / DATTO defaults).
	function _status(oFrom, oTo) {
		var oToday = new Date();
		oToday.setHours(0, 0, 0, 0);
		if (oTo && oTo < oToday) {
			return STATUS.EXPIRED;
		}
		if (oFrom && oFrom > oToday) {
			return STATUS.UPCOMING;
		}
		return STATUS.ACTIVE;
	}

	// Open-ended validity (DATTO = 99991231) is shown as an empty Valid To.
	function _toValidTo(d) {
		var oDate = _toLocalDate(d);
		return oDate && oDate.getFullYear() === 9999 ? null : oDate;
	}

	function _toCampaign(r) {
		var oFrom = _toLocalDate(r[FIELD.validFrom]);
		var oTo = _toValidTo(r[FIELD.validTo]);
		var sStatus = _status(oFrom, oTo);
		return {
			id: r[FIELD.id],
			description: r[FIELD.description] || "",
			country: r[FIELD.country] || "",
			countryName: _countryName(r[FIELD.country]),
			createdOn: _parseYmd(r[FIELD.createdOn]),
			createdBy: r[FIELD.createdBy] || "",
			changedOn: null,
			changedBy: "",
			validFrom: oFrom,
			validTo: oTo,
			status: sStatus,
			statusState: STATUS_STATE[sStatus] || "None"
		};
	}

	function _countryName(sLand) {
		var oCountry = ((_oModel && _oModel.getProperty("/countries")) || []).find(function (c) { return c.Land1 === sLand; });
		return oCountry ? oCountry.Landx : (sLand || "");
	}

	function _isAllowedCountry(sLand) {
		return ALLOWED_COUNTRIES.indexOf(String(sLand || "").trim().toUpperCase()) !== -1;
	}

	// The location's country: the selected store's country, else the sales employee's. Left empty
	// when it is not one of the allowed countries.
	function _userCountry() {
		var sLand = (_oModel.getProperty("/storeCountry") || _sEmployeeCountry || "").trim().toUpperCase();
		return _isAllowedCountry(sLand) ? sLand : "";
	}

	// The store picked in the sales order app is kept in localStorage; read its country from StoreSet.
	function _loadStoreCountry() {
		var sStoreId = _storedStoreId();
		if (_oModel.getProperty("/storeCountry") || !sStoreId) {
			return Promise.resolve();
		}
		return _read("/StoreSet", { filters: [new Filter("StoreId", FilterOperator.EQ, sStoreId)] }).then(function (aStores) {
			var oFound = aStores.find(function (o) { return o.StoreId === sStoreId; }) || aStores[0];
			if (oFound && oFound.Country) {
				_oModel.setProperty("/storeCountry", oFound.Country);
			}
		}).catch(function () {
			// fall back to the sales employee's country
		});
	}

	// Logged-in user's e-mail (approuter user API) -> SalesEmployees -> Land. Read once; any failure
	// just leaves the default country empty.
	function _loadEmployeeCountry() {
		if (!_pEmployee) {
			var sUrl = sap.ui.require.toUrl(_oComponent.getManifestEntry("/sap.app/id").replace(/\./g, "/")) + "/user-api/attributes";
			_pEmployee = fetch(sUrl, { credentials: "same-origin" }).then(function (oResponse) {
				return oResponse.ok ? oResponse.json() : {};
			}).then(function (oUser) {
				if (!oUser.email) {
					return;
				}
				return _read("/SalesEmployees", {
					urlParameters: { StoreId: "''", Email: "'" + oUser.email + "'" }
				}).then(function (aEmployees) {
					_sEmployeeCountry = (aEmployees[0] && aEmployees[0].Land) || "";
				});
			}).catch(function () {
				// no default country
			});
		}
		return _pEmployee;
	}

	function _storedStoreId() {
		try {
			return window.localStorage.getItem("selectedStoreId") || "";
		} catch (e) {
			return "";
		}
	}

	// ---------------------------------------------------------------- validation (§12)

	// §12 checks for the campaign master. Create: Description and Country mandatory. Change: Campaign
	// ID and Description mandatory (pass the campaign ID as sChangeId); a changed country must still be
	// an allowed one.
	function validate(oDraft, sChangeId) {
		var aMsg = [];
		var bChange = sChangeId !== undefined;
		var sDesc = (oDraft.description || "").trim();
		if (bChange && !sChangeId) {
			aMsg.push(_err("Campaign ID is mandatory.", "id"));
		}
		if (!sDesc) {
			aMsg.push(_err("Campaign description is mandatory.", "description"));
		} else if (sDesc.length > DESCRIPTION_MAX) {
			aMsg.push(_err("Campaign description cannot exceed " + DESCRIPTION_MAX + " characters.", "description"));
		}
		if (!oDraft.country) {
			aMsg.push(_err("Country is mandatory.", "country"));
		} else if (!_isAllowedCountry(oDraft.country)) {
			aMsg.push(_err("Country " + oDraft.country + " is not allowed. Allowed countries: " + ALLOWED_COUNTRIES.join(", ") + ".", "country"));
		}
		return aMsg;
	}

	// ---------------------------------------------------------------- public API

	return {
		STATUS: STATUS,
		STATUS_STATE: STATUS_STATE,
		DESCRIPTION_MAX: DESCRIPTION_MAX,

		// Loads the country list once and resolves the user's default country.
		init: function (oComponent) {
			_oComponent = oComponent;
			if (!_oModel) {
				_oModel = new JSONModel({ campaigns: [], countries: [], defaultCountry: "", storeCountry: "" });
			}
			if (!_pLoad) {
				_pLoad = _read("/CountrySet", { urlParameters: { $top: 5000 } }).then(function (aCountries) {
					_oModel.setProperty("/countries", aCountries.filter(function (c) {
						return _isAllowedCountry(c.Land1);
					}));
				}).catch(function (oError) {
					_pLoad = null;
					throw oError;
				});
			}
			return Promise.all([_pLoad, _loadStoreCountry(), _loadEmployeeCountry()]).then(function () {
				_oModel.setProperty("/defaultCountry", _userCountry());
			});
		},

		getModel: function () {
			return _oModel;
		},

		getDefaultCountry: function () {
			return _oModel.getProperty("/defaultCountry");
		},

		// §4.3 search: campaign ID / description (contains), countries, created by, created on range.
		// Countries and an exact campaign ID go to the backend as $filter; contains-text, created by and
		// the created-on range (Credate is a YYYYMMDD string) are applied here. No countries selected
		// means all allowed countries.
		search: function (oCriteria) {
			var c = oCriteria || {};
			var aFilters = [];
			var sId = (c.campaign || "").trim().toUpperCase();
			if (/^C-\d+$/.test(sId)) {
				aFilters.push(new Filter(FIELD.id, FilterOperator.EQ, sId));
			}
			var aCountries = (c.countries || []).filter(_isAllowedCountry);
			if (aCountries.length) {
				aFilters.push(new Filter({
					filters: aCountries.map(function (sLand) {
						return new Filter(FIELD.country, FilterOperator.EQ, sLand);
					}),
					and: false
				}));
			}
			var sText = (c.campaign || "").trim().toLowerCase();
			var sBy = (c.createdBy || "").toUpperCase();
			var oFrom = c.from ? new Date(c.from.getFullYear(), c.from.getMonth(), c.from.getDate()) : null;
			var oTo = c.to || c.from;
			oTo = oTo ? new Date(oTo.getFullYear(), oTo.getMonth(), oTo.getDate()) : null;
			return _read(CAMPAIGN_SET, { filters: aFilters }).then(function (aRows) {
				var aCampaigns = aRows.map(_toCampaign).filter(function (o) {
					return (!sText || (o.id + " " + o.description).toLowerCase().indexOf(sText) !== -1) &&
						(aCountries.length ? aCountries.indexOf(o.country) !== -1 : _isAllowedCountry(o.country)) &&
						(!sBy || o.createdBy.toUpperCase().indexOf(sBy) !== -1) &&
						(!oFrom || (o.createdOn && o.createdOn >= oFrom && o.createdOn <= oTo));
				});
				_oModel.setProperty("/campaigns", aCampaigns);
				return aCampaigns;
			});
		},

		// The campaign as last loaded in the list (shown at once while get() reads the backend).
		getCached: function (sId) {
			return ((_oModel && _oModel.getProperty("/campaigns")) || []).find(function (o) { return o.id === sId; }) || null;
		},

		// Picks the row with this exact ID, so a backend that ignores the $filter cannot return
		// another campaign.
		get: function (sId) {
			return _read(CAMPAIGN_SET, { filters: [new Filter(FIELD.id, FilterOperator.EQ, sId)] }).then(function (aRows) {
				var oRow = aRows.find(function (r) { return r[FIELD.id] === sId; });
				if (!oRow) {
					throw _throw(_err("Campaign " + sId + " not found."));
				}
				return _toCampaign(oRow);
			});
		},

		validate: validate,

		// §4.1: the backend allocates the ZCAMPAIGN number; never send a client-generated ID.
		create: function (oDraft) {
			var aMsg = validate(oDraft);
			if (aMsg.length) {
				return Promise.reject(_throw(aMsg));
			}
			return _post(_payload("", oDraft)).then(function (oData) {
				if (!oData[FIELD.id]) {
					throw _throw(_err("The campaign was not created: no campaign ID was returned."));
				}
				return _toCampaign(oData);
			});
		},

		// Change: POST to the same entity with the same payload as create, CampaignId filled. Creation
		// data is never sent (Appendix A: no broad MODIFY of the row). Resolves with the updated
		// campaign, which also replaces the list's copy.
		update: function (sId, oDraft, oOriginal) {
			var aMsg = validate(oDraft, sId);
			if (aMsg.length) {
				return Promise.reject(_throw(aMsg));
			}
			var oPayload = _payload(sId, oDraft);
			return _post(oPayload).then(function () {
				// Validity is not sent, so the original dates and status stay.
				var oUpdated = Object.assign({}, oOriginal, {
					description: oPayload[FIELD.description],
					country: oDraft.country,
					countryName: _countryName(oDraft.country)
				});
				var aList = _oModel.getProperty("/campaigns") || [];
				var i = aList.findIndex(function (o) { return o.id === sId; });
				if (i !== -1) {
					aList[i] = oUpdated;
				}
				return oUpdated;
			});
		}
	};
});
